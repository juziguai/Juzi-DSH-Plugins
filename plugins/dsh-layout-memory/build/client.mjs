import { readFile, writeFile } from 'node:fs/promises';
const base = new URL('../', import.meta.url);
const sources = await Promise.all(['lib/memory.js', 'src/client.mjs'].map(file => readFile(new URL(file, base), 'utf8')));
const body = sources.map(text => text.replace(/^import .*;\r?\n/gm, '').replace(/^export /gm, '')).join('\n');
const output = `// Generated by build/client.mjs; edit lib/memory.js and src/client.mjs.\nwindow.__ModuleLoader__.load({id:'@juzi/dsh-layout-memory',factory:(require)=>{\n${body}\nreturn {inject,apply};\n}});\n`;
const target = new URL('lib/client.js', base);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== output) throw new Error('Layout memory client is stale; run node plugins/dsh-layout-memory/build/client.mjs');
} else await writeFile(target, output);
