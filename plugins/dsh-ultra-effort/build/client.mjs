import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import { createModelLabel } from '../src/model-label.mjs';
import { CSS, ULTRA_CSS } from '../src/styles.mjs';

const root = new URL('../', import.meta.url);

export function renderClient() {
  const versions = JSON.parse(readFileSync(new URL('src/model-versions.json', root), 'utf8'));
  for (const [id, entry] of Object.entries(versions)) {
    assert(id.startsWith('deepseek-') && typeof entry.full === 'string' && typeof entry.badge === 'string', `invalid model version: ${id}`);
  }
  let client = readFileSync(new URL('src/client.template.js', root), 'utf8');
  for (const [key, value] of Object.entries({
    MODEL_LABEL_FACTORY: createModelLabel.toString(), MODEL_VERSIONS: JSON.stringify(versions, null, 2),
    CSS: JSON.stringify(CSS), ULTRA_CSS: JSON.stringify(ULTRA_CSS),
  })) {
    const token = `__${key}__`;
    assert.equal(client.split(token).length, 2, `expected one ${token}`);
    client = client.replace(token, () => value);
  }
  return '// Generated by build/client.mjs; edit src/ modules and run npm run client:build.\n' + client;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const path = new URL('lib/client.js', root);
  const client = renderClient();
  if (process.argv.includes('--check')) assert.equal(readFileSync(path, 'utf8'), client, 'Ultra client drift: run npm run client:build');
  else writeFileSync(path, client);
}
